def run_of(notes): return f"(select \"runId\" from \"consolidationRun\" where \"notes\" = '{notes}')"

EFFECTS = {"Volumen": "VOLUMEN", "Precio": "PRECIO", "Tipo de cambio": "TIPO_CAMBIO", "Costo de ventas (operativo)": "COSTO_VENTAS",
           "Gasto operativo": "GASTO_OPERATIVO", "IC (neutral en consolidado)": "IC_NEUTRAL",
           "EBIT operativo (después de impuestos)": "EBIT_DESPUES_IMPUESTOS", "Tasa de impuesto efectiva (mezcla de países)": "TASA_IMPUESTO",
           "Parámetro WACC": "WACC", "Capital invertido": "CAPITAL_INVERTIDO"}
def eff(label): return t(EFFECTS[label])  # KeyError on an unknown label: fail loudly

def run_tables(notes, pre):
    """Reconciliation, eliminations, consolidated balances and lineage of a reference run (CSVs <pre>_*.csv)."""
    def load(table, cols, rows, fn):
        return (f'insert into "{table}" ("runId", ' + ", ".join(f'"{c}"' for c in cols) + ")\n"
                f"select r.\"runId\", v.* from (select \"runId\" from \"consolidationRun\" where \"notes\" = '{notes}') r, (values\n"
                + vals(rows, fn) + ")\nas v(" + ", ".join(f"c{i}" for i in range(len(cols))) + ");")
    return [
      load("icReconciliation", ["icDocumentId", "financialStatementCode", "issuerCompanyId", "receiverCompanyId", "statusCode", "issuerUsd", "receiverUsd", "differenceUsd", "lineRefs"],
           rd(f"{R}/{pre}_conciliacion_ic.csv"), lambda r: [t(r["doc_ic_id"]), t(r["estado_financiero"]), t(r["emisor"]), t(r["receptor"]), t(r["estado"]),
                                                            n(r["usd_emisor"]), n(r["usd_receptor"]), n(r["diferencia_usd"]), t(r["lineas"])]),
      load("elimination", ["eliminationCode", "eliminationRuleCode", "icDocumentId", "companyId", "groupAccountId", "effectUsd", "sourceRef"],
           rd(f"{R}/{pre}_eliminaciones.csv"), lambda r: [t(r["elim_id"]), t(r["regla"]), t(r["doc_ic_id"]), g(r["empresa"]), t(r["cuenta_grupo"]), n(r["efecto_usd"]), t(r["origen"])]),
      load("consolidatedBalance", ["groupAccountId", "aggregatedUsd", "eliminationsUsd", "translationAdjustmentUsd"],
           rd(f"{R}/{pre}_consolidado.csv"), lambda r: [t(r["cuenta_grupo"]), n(r["agregado"] or 0), n(r["eliminaciones"] or 0), n(r["cta_conversion"] or 0)]),
      load("lineage", ["groupAccountId", "sourceTypeCode", "sourceId", "companyId", "localAmount", "currencyCode", "rate", "contributionUsd"],
           rd(f"{R}/{pre}_linaje.csv"), lambda r: [t(r["cuenta_grupo"]), t(r["origen_tipo"]), t(r["origen_id"]), g(r["empresa"]), n(r["monto_local"]),
                                                   t(r["moneda"]), n(r["tasa"], 10), n(r["aporte_usd"])]),
      f"""update "consolidationRun" set "lineageOk" = not exists (
  select 1 from "consolidatedBalance" c
   where c."runId" = {run_of(notes)}
     and abs(c."consolidatedUsd" - coalesce((select sum(l."contributionUsd") from "lineage" l
                                              where l."runId" = c."runId" and l."groupAccountId" = c."groupAccountId"), 0)) > 1)
 where "runId" = {run_of(notes)};"""]

def rate_fix():
    key = lambda r: (r["escenario"], r["periodo"], r["moneda"], r["tipo_tasa"])
    old = {key(r): r["tasa_a_usd"] for r in rd(f"{D}/tasas/tasas_grupo_V1.csv")}
    out = ["set local app.change_reason = 'Fix E01: inverted MXN PRESUPUESTO rate 2027-05 (finding V08)';"]
    for r in rd(f"{BASE}/_respuestas/tasas_grupo_V1_corregida.csv"):
        if old[key(r)] != r["tasa_a_usd"]:
            out.append(f'update "groupExchangeRate" set "rateToUsd" = {r["tasa_a_usd"]} where "scenarioId" = \'{r["escenario"]}\' and "periodCode" = \'{r["periodo"]}\''
                       f' and "currencyCode" = \'{r["moneda"]}\' and "rateTypeCode" = \'{r["tipo_tasa"]}\';')
    out.append("set local app.change_reason = 'Seed 06 demo data';")
    return "\n".join(out)

