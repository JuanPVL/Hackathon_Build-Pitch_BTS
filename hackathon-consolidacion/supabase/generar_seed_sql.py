NUMERICAS = {"decimales", "tasa_isr", "valor", "tasa_a_usd", "pct_min", "pct_max", "monto", "monto_tx", "volumen", "precio"}

BOOLS = {"es_ic", "corriente"}

def q(v, col=""):
    if col in BOOLS:
        return "null::boolean" if v in (None, "") else v
    if v is None or v == "":
        return "null::numeric" if col in NUMERICAS else "null::text"
    if col in NUMERICAS:
        return f"{float(v)!r}::numeric" if col in ("monto", "monto_tx", "volumen", "precio") else str(v)
    return "'" + str(v).replace("'", "''") + "'"

def ins(tabla, cols, rows):
    """cols = [(csv_col, "sqlCol"), ...]; CSV names stay Spanish, SQL identifiers are quoted camelCase."""
    out = [f'insert into "{tabla}" ({", ".join(chr(34) + n + chr(34) for _, n in cols)}) values']
    out.append(",\n".join("  (" + ", ".join(q(r[c], c) for c, _ in cols) + ")" for r in rows) + ";")
    return "\n".join(out)

def rd(p):
    with open(p, encoding="utf-8") as f:
        return list(csv.DictReader(f))

