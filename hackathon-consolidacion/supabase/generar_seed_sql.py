def maestros():
    S = ["-- Generated by generar_seed_sql.py: master data, scenarios, parameters, rates and validation rules", "begin;"]
    S.append(ins("currency", [("moneda_id", "currencyCode"), ("nombre", "name"), ("decimales", "decimalPlaces")], rd(f"{D}/maestros/monedas.csv")))
    S.append(ins("company", [("empresa_id", "companyId"), ("nombre", "name"), ("pais", "countryCode"), ("moneda_funcional", "functionalCurrencyCode"),
                             ("id_fiscal", "taxId"), ("tasa_isr", "incomeTaxRate")], rd(f"{D}/maestros/empresas.csv")))
    ctas = rd(f"{D}/maestros/cuentas_grupo.csv")
    for c in ctas:
        c["es_ic"] = "true" if c["es_ic"] == "1" else "false"
        c["corriente"] = {"S": "true", "N": "false"}.get(c["corriente"], "")
    S.append(ins("groupAccount", [("cuenta_grupo_id", "groupAccountId"), ("nombre", "name"), ("tipo", "accountTypeCode"), ("rubro", "accountCategoryCode"),
                                  ("es_ic", "isIntercompany"), ("cuenta_contraparte_ic", "icCounterAccountId"), ("corriente", "isCurrent")], ctas))
    S.append("-- share capital is translated at the historical rate\n"
             "update \"groupAccount\" set \"rateTypeCode\" = 'HISTORICA' where \"groupAccountId\" = '3100';")
    S.append("-- IC document types: P&L and balance-sheet accounts (depend on the chart of accounts)\n" + ICDOC_ACCOUNTS)
    S.append(ins("accountMapping", [("pais", "countryCode"), ("cuenta_local", "localAccountCode"), ("cuenta_grupo_id", "groupAccountId")], rd(f"{D}/maestros/mapeo_cuentas.csv")))
    S.append("insert into \"scenario\" (\"scenarioId\", \"description\") values ('PPTO_V1', 'Presupuesto 2027 versión 1'), ('PPTO_V2', 'Presupuesto 2027 versión 2');")
    for v in ("V1", "V2"):
        p = rd(f"{D}/maestros/parametros_{v}.csv")
        for r in p:
            r["escenario_id"] = r.pop("escenario")
        S.append(ins("parameter", [("escenario_id", "scenarioId"), ("parametro", "parameterCode"), ("valor", "value"), ("descripcion", "description")], p))
        t = rd(f"{D}/tasas/tasas_grupo_{v}.csv")
        for r in t:
            r["escenario_id"] = r.pop("escenario"); r["moneda_id"] = r.pop("moneda")
        S.append(f"-- rates {v}" + (" (CONTAINS seeded error E01: the validator must find it)" if v == "V1" else ""))
        S.append(ins("groupExchangeRate", [("escenario_id", "scenarioId"), ("periodo", "periodCode"), ("moneda_id", "currencyCode"),
                                           ("tipo_tasa", "rateTypeCode"), ("tasa_a_usd", "rateToUsd")], t))
    S.append(ins("transferPricingPolicy", [("politica_id", "policyId"), ("tipo_ic", "icDocumentTypeCode"), ("descripcion", "description"),
                                           ("pct_min", "minPct"), ("pct_max", "maxPct")], rd(f"{D}/maestros/politicas_tp.csv")))
    S.append(ins("validationRule", [("codigo", "ruleCode"), ("descripcion", "description"), ("severidad", "severityCode")],
                 [dict(codigo=a, descripcion=b, severidad=c) for a, b, c in REGLAS]))
