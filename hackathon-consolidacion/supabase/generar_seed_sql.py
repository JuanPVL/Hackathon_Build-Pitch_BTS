def t(v):  return "null::text" if v in (None, "") else "'" + v.replace("'", "''") + "'::text"
def n(v, d=2): return "null::numeric" if v in (None, "") else f"{round(float(v), d)!r}::numeric"
def g(v):  return "null::text" if v in (None, "", "GRUPO") else t(v)

def vals(rows, fn):
    return ",\n".join("  (" + ", ".join(fn(r)) + ")" for r in rows)

